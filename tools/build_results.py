"""Regenerate the tables of `results/` from the frozen snapshot.

    python tools/build_results.py            # writes ARTICLE_NUMBERS.md and STUDIES.md
    python tools/build_results.py --check    # fails if the committed tables are out of date

`ARTICLE_NUMBERS.md` lists every number that the article states and that is checked against a
sealed summary. The values are produced by the frozen script that checks the manuscript
(`as_run/scripts/check_manuscript_numbers.py`), run here without a manuscript, so that only what
it derives from the sealed packages is used.
"""

from __future__ import annotations

import argparse
import contextlib
import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SNAPSHOT = os.path.join(ROOT, "as_run")
RESULTS = os.path.join(ROOT, "results")
CATALOGUE = os.path.join(ROOT, "src", "pursuit_audit", "evidence", "studies.json")
CHECKER = os.path.join(SNAPSHOT, "scripts", "check_manuscript_numbers.py")
COLLECTOR = "    checks = []\n"


def sealed_values() -> list[tuple[str, str]]:
    """Return the (label, value) pairs that the frozen checker derives from the sealed summaries.

    The checker builds that list and then looks each value up in a manuscript. Its source is run
    here from memory with the list handed in from outside, so the pairs are read exactly instead
    of being parsed back from its printed table. The file on disk is not changed.
    """
    with open(CHECKER, encoding="utf-8") as handle:
        source = handle.read()
    if source.count(COLLECTOR) != 1:
        raise SystemExit("the frozen checker no longer has the expected list of checks")
    captured: list[tuple[str, str]] = []
    namespace = {"__name__": "frozen_checker", "__file__": CHECKER, "CAPTURED": captured}
    exec(compile(source.replace(COLLECTOR, "    checks = CAPTURED\n"), CHECKER, "exec"), namespace)
    arguments, sys.argv = sys.argv, [CHECKER, "no_manuscript"]
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            namespace["main"]()
    finally:
        sys.argv = arguments
    return captured


def article_numbers() -> str:
    """Return the table of the numbers of the article, from the sealed summaries."""
    rows = sealed_values()
    lines = [
        "# Numbers of the article, from the sealed summaries",
        "",
        "Generated by `tools/build_results.py`; do not edit. Each value is formatted as the",
        "article prints it and is computed from a sealed summary by",
        "`as_run/scripts/check_manuscript_numbers.py`. `results/EVIDENCE_MAP.md` says which",
        "package, file and key hold each one.",
        "",
        f"{len(rows)} values.",
        "",
        "| Check | Value |",
        "|---|---|",
    ]
    lines += [f"| {label} | `{value}` |" for label, value in rows]
    return "\n".join(lines) + "\n"


def megabytes(count: int) -> str:
    """Format a size in bytes as megabytes, or as a dash when it is zero."""
    return f"{count / 1e6:.1f}" if count else "–"


def studies() -> str:
    """Return the table of the sealed studies, from the catalogue."""
    with open(CATALOGUE, encoding="utf-8") as handle:
        catalogue = json.load(handle)
    lines = [
        "# Studies, evidence packages and demonstrations",
        "",
        "Generated by `tools/build_results.py` from the catalogue; do not edit. One row per",
        "directory under `as_run/experiments/`: 89 sealed packages and one demo directory.",
        "A catalogue entry does not itself establish preregistration. *Article* marks what the",
        "article rests on. *Simulator* marks those whose script starts SUMO. *Archive* is the",
        "size, in megabytes, of the files of the package that are only in the data archive (run",
        "logs, training states).",
        "",
        "The commands below are starting templates for a separate working copy of `as_run/`.",
        "Use new output paths; scripts may need further arguments or depend on other packages.",
        "Inspect scripts with `--help` before running. Analysis scripts are shown with `--help`",
        "because their inputs and outputs differ; never run them against preserved packages.",
        "`REPRODUCE.md` explains the options and the budgets.",
        "",
        "| Package | Record | Article | Simulator | Archive (MB) | Script |",
        "|---|---|---|---|---|---|",
    ]
    for study in catalogue:
        scripts = ", ".join(
            f"`{name}`" for name in [study["script"], *study["analysis_scripts"]] if name
        )
        lines.append(
            f"| `{study['package']}` | {study['amendment'] or '–'} "
            f"| {'yes' if study['in_article'] else ''} "
            f"| {'yes' if study['needs_simulator'] else ''} "
            f"| {megabytes(study['archive_only_bytes'])} | {scripts or '–'} |"
        )
    lines += ["", "## Commands of the studies behind the article", ""]
    for study in catalogue:
        if not study["in_article"] or not study["command"]:
            continue
        lines += [f"**{study['title']}** (`{study['package']}`)", "", "```bash"]
        lines.append(study["command"])
        lines += [f"uv run python scripts/{name} --help" for name in study["analysis_scripts"]]
        lines += ["```", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    """Write the tables, or check that the committed ones are current."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, build in (("ARTICLE_NUMBERS.md", article_numbers), ("STUDIES.md", studies)):
        path = os.path.join(RESULTS, name)
        text = build()
        current = ""
        if os.path.exists(path):
            with open(path, encoding="utf-8") as handle:
                current = handle.read()
        if current != text:
            stale.append(name)
            if not args.check:
                with open(path, "w", encoding="utf-8") as handle:
                    handle.write(text)
        print(f"{name}: {'changed' if current != text else 'up to date'}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
